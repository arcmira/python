"""Copy Fern output into the package, preserving the public URL constants."""
from pathlib import Path
import shutil
root = Path(__file__).resolve().parents[1]
source = root / '.generated/python'
target = root / 'src/arcmira'
assert (source / 'client.py').exists()
shutil.rmtree(target)
for path in source.rglob('*.py'):
    if 'tests' in path.relative_to(source).parts:
        continue
    dest = target / path.relative_to(source)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(path.read_text().rstrip() + '\n')
(target / 'py.typed').touch()
# Fern's ApiError.__str__ leads with headers; the override leads with status, code and message.
generated_error = (target / 'core/api_error.py').read_text()
assert 'class ApiError(Exception)' in generated_error
(target / 'core/api_error.py').write_text((root / 'scripts/overrides/api_error.py').read_text())
# The previous public pointer package exported these constants.
init = target / '__init__.py'
text = init.read_text()
assert text.startswith('# This file was auto-generated by Fern')
init.write_text(text + '\nfrom ._package import __version__, homepage, docs, api_base, openapi, llms_txt, docs_llms_txt\n')
version = (root / 'VERSION').read_text().strip()
(target / '_package.py').write_text(f'''# Written by scripts/install-generated.py from VERSION.
__version__ = {version!r}
homepage = "https://arcmira.com"
docs = "https://arcmira.com/docs"
api_base = "https://api.arcmira.com/v1"
openapi = "https://api.arcmira.com/v1/openapi.json"
llms_txt = "https://arcmira.com/llms.txt"
docs_llms_txt = "https://arcmira.com/docs/llms.txt"
''')
reference = (source / 'reference.md').read_text()
(root / 'reference.md').write_text('\n'.join(line.rstrip() for line in reference.splitlines()).rstrip() + '\n')
